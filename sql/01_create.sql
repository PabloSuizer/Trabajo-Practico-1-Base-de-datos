CREATE DATABASE IF NOT EXISTS biblioteca_universitaria;
USE biblioteca_universitaria;

-- Nivel 1: Tablas independientes (fuertes)
CREATE TABLE CIUDAD (
    ID_CIUDAD INT AUTO_INCREMENT PRIMARY KEY,
    NOMBRE VARCHAR(100) NOT NULL
);

CREATE TABLE TIPO (
    ID_TIPO INT AUTO_INCREMENT PRIMARY KEY,
    TIPO_P VARCHAR(50) NOT NULL
);

CREATE TABLE BIBLIOTECA (
    ID_BIBLIO INT AUTO_INCREMENT PRIMARY KEY,
    BIBLIOTECA VARCHAR(100) NOT NULL
);

CREATE TABLE EDITORIALES (
    ID_EDIT INT AUTO_INCREMENT PRIMARY KEY,
    NOMBRE VARCHAR(100) NOT NULL,
    PAIS VARCHAR(60) NOT NULL
);

CREATE TABLE AUTORES (
    RUT_AUTOR VARCHAR(12) PRIMARY KEY,
    NOMBRES VARCHAR(100) NOT NULL,
    APELLIDOS VARCHAR(100) NOT NULL
);

-- Nivel 2: Tablas con dependencia de Nivel 1
CREATE TABLE CAMPUS (
    ID_CAMPUS INT AUTO_INCREMENT PRIMARY KEY,
    NOMBRE VARCHAR(100) NOT NULL,
    FK1_ID_CIUDAD INT NOT NULL,
    CONSTRAINT fk_campus_ciudad FOREIGN KEY (FK1_ID_CIUDAD) REFERENCES CIUDAD(ID_CIUDAD)
);

-- Nivel 3: Tablas con dependencia de CAMPUS
CREATE TABLE CARRERAS (
    ID_CARRERA INT AUTO_INCREMENT PRIMARY KEY,
    NOMBRE VARCHAR(100) NOT NULL,
    FK1_ID_CAMPUS INT NOT NULL,
    CONSTRAINT fk_carreras_campus FOREIGN KEY (FK1_ID_CAMPUS) REFERENCES CAMPUS(ID_CAMPUS)
);

CREATE TABLE FUNCIONARIOS (
    RUT_FUNC VARCHAR(12) PRIMARY KEY,
    NOMBRES VARCHAR(100) NOT NULL,
    APELLIDOS VARCHAR(100) NOT NULL,
    EDAD INT NOT NULL,
    DIRECCION VARCHAR(150),
    SALUD VARCHAR(50) NOT NULL,
    FK1_ID_CAMPUS INT NOT NULL,
    CONSTRAINT fk_funcionarios_campus FOREIGN KEY (FK1_ID_CAMPUS) REFERENCES CAMPUS(ID_CAMPUS)
);

-- Nivel 4: Tablas con dependencia de CARRERAS y catálogos
CREATE TABLE ESTUDIANTES (
    RUT_EST VARCHAR(12) PRIMARY KEY,
    NOMBRES VARCHAR(100) NOT NULL,
    APELLIDOS VARCHAR(100) NOT NULL,
    EDAD INT NOT NULL,
    FONO VARCHAR(20),
    DIRECCION VARCHAR(150),
    FK1_ID_CARRERA INT NOT NULL,
    CONSTRAINT fk_estudiantes_carreras FOREIGN KEY (FK1_ID_CARRERA) REFERENCES CARRERAS(ID_CARRERA)
);

CREATE TABLE LIBROS (
    COD_LIBRO INT PRIMARY KEY,
    TITULO VARCHAR(150) NOT NULL,
    AGNO INT NOT NULL,
    FK1_ID_BIBLIO INT NOT NULL,
    FK2_ID_TIPO INT NOT NULL,
    FK3_RUT_AUTOR VARCHAR(12) NOT NULL,
    FK4_ID_EDIT INT NOT NULL,
    CONSTRAINT fk_libros_biblioteca FOREIGN KEY (FK1_ID_BIBLIO) REFERENCES BIBLIOTECA(ID_BIBLIO),
    CONSTRAINT fk_libros_tipo FOREIGN KEY (FK2_ID_TIPO) REFERENCES TIPO(ID_TIPO),
    CONSTRAINT fk_libros_autor FOREIGN KEY (FK3_RUT_AUTOR) REFERENCES AUTORES(RUT_AUTOR),
    CONSTRAINT fk_libros_editorial FOREIGN KEY (FK4_ID_EDIT) REFERENCES EDITORIALES(ID_EDIT)
);

-- Nivel 5: Tabla transaccional
CREATE TABLE PRESTAMO (
    RUT_EST VARCHAR(12) NOT NULL,
    RUT_FUNC VARCHAR(12) NOT NULL,
    COD_LIBRO INT NOT NULL,
    FECHA_P DATE NOT NULL,
    FECHA_E DATE,
    PRIMARY KEY (RUT_EST, RUT_FUNC, COD_LIBRO),
    CONSTRAINT fk_prestamo_estudiante FOREIGN KEY (RUT_EST) REFERENCES ESTUDIANTES(RUT_EST),
    CONSTRAINT fk_prestamo_funcionario FOREIGN KEY (RUT_FUNC) REFERENCES FUNCIONARIOS(RUT_FUNC),
    CONSTRAINT fk_prestamo_libro FOREIGN KEY (COD_LIBRO) REFERENCES LIBROS(COD_LIBRO)
);