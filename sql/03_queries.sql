USE biblioteca_universitaria;

-- 1. Título y año de todos los libros ordenados del más antiguo al más nuevo
SELECT TITULO, AGNO FROM LIBROS ORDER BY AGNO ASC;

-- 2. Nombre, apellido y edad de estudiantes mayores de 25 años
SELECT NOMBRES, APELLIDOS, EDAD FROM ESTUDIANTES WHERE EDAD > 25;

-- 3. Título y año de libros de la editorial con ID_EDIT = 3
SELECT TITULO, AGNO FROM LIBROS WHERE FK4_ID_EDIT = 3;

-- 4. Todos los datos de autores cuyo apellido comience con "M"
SELECT * FROM AUTORES WHERE APELLIDOS LIKE 'M%';

-- 5. Funcionarios con salud distinta a "Buena"
SELECT NOMBRES, APELLIDOS, SALUD FROM FUNCIONARIOS WHERE SALUD <> 'Buena';

-- 6. Título del libro junto con nombre y apellido de su autor
SELECT L.TITULO, A.NOMBRES, A.APELLIDOS 
FROM LIBROS L
INNER JOIN AUTORES A ON L.FK3_RUT_AUTOR = A.RUT_AUTOR;

-- 7. Préstamo con detalle: Fecha, Estudiante, Libro y Funcionario
SELECT 
    P.FECHA_P,
    CONCAT(E.NOMBRES, ' ', E.APELLIDOS) AS ESTUDIANTE,
    L.TITULO,
    CONCAT(F.NOMBRES, ' ', F.APELLIDOS) AS FUNCIONARIO
FROM PRESTAMO P
INNER JOIN ESTUDIANTES E ON P.RUT_EST = E.RUT_EST
INNER JOIN LIBROS L ON P.COD_LIBRO = L.COD_LIBRO
INNER JOIN FUNCIONARIOS F ON P.RUT_FUNC = F.RUT_FUNC;

-- 8. Nombre del estudiante, carrera y ciudad donde estudia
SELECT 
    CONCAT(E.NOMBRES, ' ', E.APELLIDOS) AS ESTUDIANTE,
    CA.NOMBRE AS CARRERA,
    CI.NOMBRE AS CIUDAD
FROM ESTUDIANTES E
INNER JOIN CARRERAS CA ON E.FK1_ID_CARRERA = CA.ID_CARRERA
INNER JOIN CAMPUS CM ON CA.FK1_ID_CAMPUS = CM.ID_CAMPUS
INNER JOIN CIUDAD CI ON CM.FK1_ID_CIUDAD = CI.ID_CIUDAD;

-- 9. Título del libro, editorial y país de origen
SELECT L.TITULO, ED.NOMBRE AS EDITORIAL, ED.PAIS
FROM LIBROS L
INNER JOIN EDITORIALES ED ON L.FK4_ID_EDIT = ED.ID_EDIT;

-- 10. Título del libro y biblioteca física donde se encuentra
SELECT L.TITULO, B.BIBLIOTECA
FROM LIBROS L
INNER JOIN BIBLIOTECA B ON L.FK1_ID_BIBLIO = B.ID_BIBLIO;

-- 11. Cantidad de libros por tipo
SELECT T.TIPO_P, COUNT(L.COD_LIBRO) AS CANTIDAD
FROM TIPO T
LEFT JOIN LIBROS L ON T.ID_TIPO = L.FK2_ID_TIPO
GROUP BY T.ID_TIPO, T.TIPO_P;

-- 12. Edad promedio de los estudiantes por carrera
SELECT CA.NOMBRE AS CARRERA, AVG(E.EDAD) AS EDAD_PROMEDIO
FROM CARRERAS CA
INNER JOIN ESTUDIANTES E ON CA.ID_CARRERA = E.FK1_ID_CARRERA
GROUP BY CA.ID_CARRERA, CA.NOMBRE;

-- 13. Funcionario y cantidad total de préstamos realizados (mayor a menor)
SELECT 
    CONCAT(F.NOMBRES, ' ', F.APELLIDOS) AS FUNCIONARIO,
    COUNT(P.COD_LIBRO) AS TOTAL_PRESTAMOS
FROM FUNCIONARIOS F
LEFT JOIN PRESTAMO P ON F.RUT_FUNC = P.RUT_FUNC
GROUP BY F.RUT_FUNC, F.NOMBRES, F.APELLIDOS
ORDER BY TOTAL_PRESTAMOS DESC;

-- 14. Autores con más de 1 libro registrado
SELECT A.NOMBRES, A.APELLIDOS, COUNT(L.COD_LIBRO) AS TOTAL_LIBROS
FROM AUTORES A
INNER JOIN LIBROS L ON A.RUT_AUTOR = L.FK3_RUT_AUTOR
GROUP BY A.RUT_AUTOR, A.NOMBRES, A.APELLIDOS
HAVING COUNT(L.COD_LIBRO) > 1;

-- 15. Nombre de la ciudad y cantidad de estudiantes que viven / estudian allí
SELECT CI.NOMBRE AS CIUDAD, COUNT(E.RUT_EST) AS CANTIDAD_ESTUDIANTES
FROM CIUDAD CI
INNER JOIN CAMPUS CM ON CI.ID_CIUDAD = CM.FK1_ID_CIUDAD
INNER JOIN CARRERAS CA ON CM.ID_CAMPUS = CA.FK1_ID_CAMPUS
INNER JOIN ESTUDIANTES E ON CA.ID_CARRERA = E.FK1_ID_CARRERA
GROUP BY CI.ID_CIUDAD, CI.NOMBRE;

-- 16. Título y año del libro más antiguo
SELECT TITULO, AGNO
FROM LIBROS
ORDER BY AGNO ASC
LIMIT 1;

-- 17. Estudiantes que nunca han pedido un libro prestado
SELECT E.RUT_EST, CONCAT(E.NOMBRES, ' ', E.APELLIDOS) AS ESTUDIANTE
FROM ESTUDIANTES E
LEFT JOIN PRESTAMO P ON E.RUT_EST = P.RUT_EST
WHERE P.COD_LIBRO IS NULL;

-- 18. Libros nunca prestados
SELECT L.COD_LIBRO, L.TITULO
FROM LIBROS L
LEFT JOIN PRESTAMO P ON L.COD_LIBRO = P.COD_LIBRO
WHERE P.COD_LIBRO IS NULL;

-- 19. Préstamos realizados en el mes calendario anterior
SELECT *
FROM PRESTAMO
WHERE FECHA_P >= DATE_SUB(DATE_FORMAT(CURDATE(), '%Y-%m-01'), INTERVAL 1 MONTH)
  AND FECHA_P < DATE_FORMAT(CURDATE(), '%Y-%m-01');

-- 20. Los 3 libros más prestados
SELECT L.TITULO, COUNT(P.COD_LIBRO) AS VECES_PRESTADO
FROM LIBROS L
INNER JOIN PRESTAMO P ON L.COD_LIBRO = P.COD_LIBRO
GROUP BY L.COD_LIBRO, L.TITULO
ORDER BY VECES_PRESTADO DESC
LIMIT 3;