USE biblioteca_universitaria;

-- Tabla de auditoría requerida por el punto 1
CREATE TABLE IF NOT EXISTS AUDITORIA_PRESTAMOS (
    ID_AUDITORIA INT AUTO_INCREMENT PRIMARY KEY,
    RUT_EST VARCHAR(12) NOT NULL,
    COD_LIBRO INT NOT NULL,
    FECHA_REGISTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    ACCION VARCHAR(50) NOT NULL
);

-- Trigger 1: Auditoría posterior a nuevo préstamo
DELIMITER //
CREATE TRIGGER TR_AUDITAR_PRESTAMO
AFTER INSERT ON PRESTAMO
FOR EACH ROW
BEGIN
    INSERT INTO AUDITORIA_PRESTAMOS (RUT_EST, COD_LIBRO, FECHA_REGISTRO, ACCION)
    VALUES (NEW.RUT_EST, NEW.COD_LIBRO, NOW(), 'NUEVO PRÉSTAMO');
END //
DELIMITER ;

-- Trigger 2: Validación de edad antes de insertar o actualizar estudiante
DELIMITER //
CREATE TRIGGER TR_VALIDAR_EDAD_ESTUDIANTE_INSERT
BEFORE INSERT ON ESTUDIANTES
FOR EACH ROW
BEGIN
    IF NEW.EDAD < 17 THEN
        SIGNAL SQLSTATE '45000'
        SET MESSAGE_TEXT = 'Error: El estudiante debe tener al menos 17 años para registrarse';
    END IF;
END //

CREATE TRIGGER TR_VALIDAR_EDAD_ESTUDIANTE_UPDATE
BEFORE UPDATE ON ESTUDIANTES
FOR EACH ROW
BEGIN
    IF NEW.EDAD < 17 THEN
        SIGNAL SQLSTATE '45000'
        SET MESSAGE_TEXT = 'Error: El estudiante debe tener al menos 17 años para registrarse';
    END IF;
END //
DELIMITER ;