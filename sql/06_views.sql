USE biblioteca_universitaria;

-- 1. Vista de detalle amigable de préstamos
CREATE OR REPLACE VIEW VW_PRESTAMOS_DETALLE AS
SELECT 
    P.FECHA_P AS FECHA_PRESTAMO,
    CONCAT(E.NOMBRES, ' ', E.APELLIDOS) AS NOMBRE_ESTUDIANTE,
    L.TITULO AS TITULO_LIBRO,
    CONCAT(F.NOMBRES, ' ', F.APELLIDOS) AS NOMBRE_FUNCIONARIO,
    CA.NOMBRE AS CARRERA_ESTUDIANTE
FROM PRESTAMO P
INNER JOIN ESTUDIANTES E ON P.RUT_EST = E.RUT_EST
INNER JOIN LIBROS L ON P.COD_LIBRO = L.COD_LIBRO
INNER JOIN FUNCIONARIOS F ON P.RUT_FUNC = F.RUT_FUNC
INNER JOIN CARRERAS CA ON E.FK1_ID_CARRERA = CA.ID_CARRERA;

-- 2. Vista de cantidad de libros por biblioteca
CREATE OR REPLACE VIEW VW_LIBROS_POR_BIBLIOTECA AS
SELECT 
    B.BIBLIOTECA,
    COUNT(L.COD_LIBRO) AS TOTAL_LIBROS
FROM BIBLIOTECA B
LEFT JOIN LIBROS L ON B.ID_BIBLIO = L.FK1_ID_BIBLIO
GROUP BY B.ID_BIBLIO, B.BIBLIOTECA;