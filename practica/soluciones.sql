-- 4.1
SELECT B.BIBLIOTECA, COUNT(L.COD_LIBRO) AS TOTAL_LIBROS
FROM BIBLIOTECA B
LEFT JOIN LIBROS L ON B.ID_BIBLIO = L.FK1_ID_BIBLIO
GROUP BY B.ID_BIBLIO, B.BIBLIOTECA
ORDER BY TOTAL_LIBROS DESC;

-- 4.2  (WHERE filtra filas ANTES de agrupar; HAVING filtra grupos DESPUÉS)
SELECT CONCAT(E.NOMBRES, ' ', E.APELLIDOS) AS ESTUDIANTE,
       COUNT(*) AS CANT_PRESTAMOS
FROM PRESTAMO P
INNER JOIN ESTUDIANTES E ON P.RUT_EST = E.RUT_EST
GROUP BY E.RUT_EST, E.NOMBRES, E.APELLIDOS
HAVING COUNT(*) > 1;

-- 4.3
SELECT ED.NOMBRE, COUNT(L.COD_LIBRO) AS CANT_LIBROS
FROM EDITORIALES ED
INNER JOIN LIBROS L ON ED.ID_EDIT = L.FK4_ID_EDIT
GROUP BY ED.ID_EDIT, ED.NOMBRE
HAVING COUNT(L.COD_LIBRO) > 2;

-- 4.4
SELECT SALUD, ROUND(AVG(EDAD), 1) AS EDAD_PROMEDIO, COUNT(*) AS CANTIDAD
FROM FUNCIONARIOS
GROUP BY SALUD;

-- 4.5
SELECT CONCAT(A.NOMBRES, ' ', A.APELLIDOS) AS AUTOR,
       COUNT(L.COD_LIBRO) AS CANT_LIBROS,
       MAX(L.AGNO) AS ULTIMO_LIBRO
FROM AUTORES A
LEFT JOIN LIBROS L ON A.RUT_AUTOR = L.FK3_RUT_AUTOR
GROUP BY A.RUT_AUTOR, A.NOMBRES, A.APELLIDOS;

-- 4.6
SELECT DATE_FORMAT(FECHA_P, '%Y-%m') AS MES, COUNT(*) AS CANT_PRESTAMOS
FROM PRESTAMO
GROUP BY DATE_FORMAT(FECHA_P, '%Y-%m')
ORDER BY MES;

