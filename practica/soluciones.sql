    WHERE L.FK3_RUT_AUTOR = A.RUT_AUTOR
);

-- 5.6  (forma simple con LIMIT; si hay empate solo muestra uno)
SELECT CONCAT(F.NOMBRES, ' ', F.APELLIDOS) AS FUNCIONARIO, COUNT(*) AS CANT
FROM PRESTAMO P
INNER JOIN FUNCIONARIOS F ON P.RUT_FUNC = F.RUT_FUNC
GROUP BY F.RUT_FUNC, F.NOMBRES, F.APELLIDOS
ORDER BY CANT DESC
LIMIT 1;

-- 5.6  (forma alternativa que respeta empates)
SELECT CONCAT(F.NOMBRES, ' ', F.APELLIDOS) AS FUNCIONARIO, COUNT(*) AS CANT
FROM PRESTAMO P
INNER JOIN FUNCIONARIOS F ON P.RUT_FUNC = F.RUT_FUNC
GROUP BY F.RUT_FUNC, F.NOMBRES, F.APELLIDOS
HAVING COUNT(*) = (
    SELECT MAX(C) FROM (SELECT COUNT(*) AS C FROM PRESTAMO GROUP BY RUT_FUNC) AS X
);

-- 5.7  (correlacionada: la subconsulta usa L1 de la consulta externa)
SELECT L1.TITULO, L1.AGNO, L1.FK2_ID_TIPO
FROM LIBROS L1
WHERE L1.AGNO = (
    SELECT MIN(L2.AGNO) FROM LIBROS L2 WHERE L2.FK2_ID_TIPO = L1.FK2_ID_TIPO
);

