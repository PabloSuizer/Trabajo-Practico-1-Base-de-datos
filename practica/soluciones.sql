-- 3.1
SELECT L.TITULO,
       T.TIPO_P AS TIPO,
       CONCAT(A.NOMBRES, ' ', A.APELLIDOS) AS AUTOR,
       ED.NOMBRE AS EDITORIAL
FROM LIBROS L
INNER JOIN TIPO T         ON L.FK2_ID_TIPO   = T.ID_TIPO
INNER JOIN AUTORES A      ON L.FK3_RUT_AUTOR = A.RUT_AUTOR
INNER JOIN EDITORIALES ED ON L.FK4_ID_EDIT   = ED.ID_EDIT;

-- 3.2
SELECT CONCAT(F.NOMBRES, ' ', F.APELLIDOS) AS FUNCIONARIO,
       CM.NOMBRE AS CAMPUS,
       CI.NOMBRE AS CIUDAD
FROM FUNCIONARIOS F
INNER JOIN CAMPUS CM ON F.FK1_ID_CAMPUS  = CM.ID_CAMPUS
INNER JOIN CIUDAD CI ON CM.FK1_ID_CIUDAD = CI.ID_CIUDAD;

-- 3.3
SELECT CONCAT(E.NOMBRES, ' ', E.APELLIDOS) AS ESTUDIANTE,
       L.TITULO,
       P.FECHA_P,
       DATEDIFF(CURDATE(), P.FECHA_P) AS DIAS_PRESTADO
FROM PRESTAMO P
INNER JOIN ESTUDIANTES E ON P.RUT_EST   = E.RUT_EST
INNER JOIN LIBROS L      ON P.COD_LIBRO = L.COD_LIBRO
WHERE P.FECHA_E IS NULL;

-- 3.4  (LEFT JOIN: conserva todas las filas de la tabla de la izquierda)
SELECT ED.NOMBRE AS EDITORIAL, L.TITULO
FROM EDITORIALES ED
LEFT JOIN LIBROS L ON ED.ID_EDIT = L.FK4_ID_EDIT
ORDER BY ED.NOMBRE;

-- 3.5  (COUNT(columna) no cuenta NULL -> da 0 para carreras sin estudiantes)
SELECT CA.NOMBRE AS CARRERA, COUNT(E.RUT_EST) AS CANT_ESTUDIANTES
FROM CARRERAS CA
LEFT JOIN ESTUDIANTES E ON CA.ID_CARRERA = E.FK1_ID_CARRERA
GROUP BY CA.ID_CARRERA, CA.NOMBRE;

-- 3.6
SELECT P.FECHA_P,
       L.TITULO,
       CONCAT(F.NOMBRES, ' ', F.APELLIDOS) AS FUNCIONARIO,
       CM.NOMBRE AS CAMPUS
FROM PRESTAMO P
INNER JOIN LIBROS L       ON P.COD_LIBRO     = L.COD_LIBRO
INNER JOIN FUNCIONARIOS F ON P.RUT_FUNC      = F.RUT_FUNC
INNER JOIN CAMPUS CM      ON F.FK1_ID_CAMPUS = CM.ID_CAMPUS;

