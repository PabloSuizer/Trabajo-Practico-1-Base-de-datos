-- 7.1  (COUNT(DISTINCT ...) evita contar estudiantes repetidos por el JOIN con PRESTAMO)
SELECT CI.NOMBRE AS CIUDAD,
       COUNT(DISTINCT E.RUT_EST) AS CANT_ESTUDIANTES,
       COUNT(P.COD_LIBRO)        AS CANT_PRESTAMOS
FROM CIUDAD CI
LEFT JOIN CAMPUS CM      ON CI.ID_CIUDAD   = CM.FK1_ID_CIUDAD
LEFT JOIN CARRERAS CA    ON CM.ID_CAMPUS   = CA.FK1_ID_CAMPUS
LEFT JOIN ESTUDIANTES E  ON CA.ID_CARRERA  = E.FK1_ID_CARRERA
LEFT JOIN PRESTAMO P     ON E.RUT_EST      = P.RUT_EST
GROUP BY CI.ID_CIUDAD, CI.NOMBRE;

-- 7.2
SELECT L.TITULO, COUNT(P.COD_LIBRO) AS VECES_PRESTADO
FROM LIBROS L
LEFT JOIN PRESTAMO P ON L.COD_LIBRO = P.COD_LIBRO
GROUP BY L.COD_LIBRO, L.TITULO
ORDER BY VECES_PRESTADO DESC, L.TITULO;

